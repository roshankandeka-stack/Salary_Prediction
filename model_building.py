import pandas as pd

df=pd.read_csv("/content/Salary Data (1).csv")

df.shape

df.isnull().sum()

df.duplicated().sum()

df.select_dtypes(include=['int64','float64'])

cat=df.select_dtypes(include=['object'])

cat.columns

df.describe()

df = pd.get_dummies(df, columns=['Gender', 'Education Level', 'Job Title'])

df.sample(10)

df.sample(10)

from sklearn.preprocessing import LabelEncoder

from sklearn.preprocessing import LabelEncoder

# Identify object-type columns (which are typically categorical)
categorical_cols = df.select_dtypes(include=['object']).columns

if not categorical_cols.empty:
    le = LabelEncoder()
    for col in categorical_cols:
        df[col] = le.fit_transform(df[col])
    print(f"LabelEncoder applied to: {categorical_cols.tolist()}")
else:
    print("No object-type categorical columns found in the DataFrame to apply LabelEncoder.")
    print("Note: 'Gender', 'Education Level', and 'Job Title' were previously one-hot encoded.")

df.sample(10)

# Drop rows with any missing values
df.dropna(inplace=True)

# Define features (x) and target (y)
x = df.drop('Salary', axis=1)
y = df['Salary']

print(f"Shape of x: {x.shape}")
print(f"Shape of y: {y.shape}")

from sklearn.model_selection import train_test_split

x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.25, random_state=42)

print(f"Shape of x_train: {x_train.shape}")
print(f"Shape of x_test: {x_test.shape}")
print(f"Shape of y_train: {y_train.shape}")
print(f"Shape of y_test: {y_test.shape}")



from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import numpy as np

# Initialize models
models = {
    'Linear Regression': LinearRegression(),
    'Decision Tree Regressor': DecisionTreeRegressor(random_state=42),
    'Random Forest Regressor': RandomForestRegressor(random_state=42),
    'Gradient Boosting Regressor': GradientBoostingRegressor(random_state=42)
}

# Dictionary to store results
results = {}

for name, model in models.items():
    print(f"\nTraining {name}...")
    # Train the model
    model.fit(x_train, y_train)

    # Make predictions
    y_pred = model.predict(x_test)

    # Evaluate the model
    mae = mean_absolute_error(y_test, y_pred)
    mse = mean_squared_error(y_test, y_pred)
    rmse = np.sqrt(mse)
    r2 = r2_score(y_test, y_pred)

    results[name] = {
        'MAE': mae,
        'MSE': mse,
        'RMSE': rmse,
        'R2 Score': r2
    }

    print(f"{name} Evaluation:")
    print(f"  Mean Absolute Error (MAE): {mae:.2f}")
    print(f"  Mean Squared Error (MSE): {mse:.2f}")
    print(f"  Root Mean Squared Error (RMSE): {rmse:.2f}")
    print(f"  R-squared (R2 Score): {r2:.2f}")

# Display all results in a DataFrame for comparison
import pandas as pd
results_df = pd.DataFrame(results).T
print("\n--- Model Comparison ---")
display(results_df)

import joblib

# Get the best performing model (Random Forest Regressor)
best_model = models['Random Forest Regressor']

# Save the model to a file
joblib.dump(best_model, 'random_forest_regressor_model.joblib')

print("Random Forest Regressor model saved successfully as 'random_forest_regressor_model.joblib'")

