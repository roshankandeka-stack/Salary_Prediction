# Extract unique values for select boxes from model_feature_columns
genders = ['Female', 'Male'] # Explicitly defined
education_levels = []
job_titles = []

for col in model_feature_columns:
    if col.startswith('Education Level_'):
        level = col.replace('Education Level_', '')
        if level not in education_levels:
            education_levels.append(level)
    elif col.startswith('Job Title_'):
        title = col.replace('Job Title_', '')
        if title not in job_titles:
            job_titles.append(title)

# Sort them for better user experience
education_levels.sort()
job_titles.sort()


# Input fields
age = st.slider("Age", min_value=18, max_value=65, value=30)
years_of_experience = st.slider("Years of Experience", min_value=0, max_value=40, value=5)
gender = st.selectbox("Gender", options=genders)
education_level = st.selectbox("Education Level", options=education_levels)
job_title = st.selectbox("Job Title", options=job_titles)


if st.button("Predict Salary"):
    # Create an empty DataFrame with all the expected feature columns, filled with zeros
    input_df = pd.DataFrame(0, index=[0], columns=model_feature_columns)

    # Populate the input_df with user selections
    input_df['Age'] = age
    input_df['Years of Experience'] = years_of_experience

    # Set one-hot encoded columns
    gender_col = f'Gender_{gender}'
    if gender_col in input_df.columns:
        input_df[gender_col] = 1

    education_col = f'Education Level_{education_level}'
    if education_col in input_df.columns:
        input_df[education_col] = 1

    job_title_col = f'Job Title_{job_title}'
    if job_title_col in input_df.columns:
        input_df[job_title_col] = 1
    else:
        st.warning(f"Selected Job Title '{job_title}' might not have been in the training data, "
                   "which could affect prediction accuracy. Using default encoding.")

    # Make prediction
    predicted_salary = model.predict(input_df)[0]

    st.success(f"Predicted Salary: ${predicted_salary:,.2f}")

